// Generates tiny blurred placeholders (LQIP) for the below-the-fold images.
// Output: src/data/placeholders.ts  — a name -> data-URI map.
//
// Re-run with `npm run placeholders` after swapping any source image.
import sharp from 'sharp';
import { readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = 'src/assets';

/** key used in components -> source file, relative to src/assets */
const TARGETS = {
  profile: 'profile-pic.png',
  coacivo: 'project/coacivo/Group 54.png',
  'rektor-cup': 'project/rektor-cup/Group 57.png',
  artiva: 'project/artiva/MacBook Air (15 inch).png',
  'artiva-gallery': 'project/artiva/Artiva Picture(1) 1.png',
};

const WIDTH = 24;
const QUALITY = 18;

async function lqip(file) {
  const buf = await sharp(file)
    .resize({ width: WIDTH })
    // Blur is what makes the upscaled placeholder read as "the same image
    // loading" rather than as a different, low-res picture.
    .blur(0.6)
    .webp({ quality: QUALITY, effort: 6 })
    .toBuffer();
  return `data:image/webp;base64,${buf.toString('base64')}`;
}

const entries = [];
let total = 0;

for (const [key, rel] of Object.entries(TARGETS)) {
  const file = join(ROOT, rel);
  const uri = await lqip(file);
  const bytes = Buffer.from(uri.split(',')[1], 'base64').length;
  total += bytes;
  entries.push([key, uri]);
  console.log(`${key.padEnd(16)} ${relative('.', file).padEnd(46)} ${String(bytes).padStart(4)} B`);
}

// Keys are always quoted: slugs like `rektor-cup` are not valid identifiers and
// would be parsed as a subtraction expression.
const body = entries.map(([k, v]) => `  '${k}': '${v}',`).join('\n');

mkdirSync('src/data', { recursive: true });
writeFileSync(
  'src/data/placeholders.ts',
  `// Generated by scripts/make-placeholders.mjs — do not edit by hand.
// Run \`npm run placeholders\` after replacing a source image.\n\nexport const placeholders: Record<string, string> = {\n${body}\n};\n`,
  'utf8',
);

console.log(`\n${entries.length} placeholders, ${(total / 1024).toFixed(1)} KB raw total -> ${'src/data/placeholders.ts'}`);
